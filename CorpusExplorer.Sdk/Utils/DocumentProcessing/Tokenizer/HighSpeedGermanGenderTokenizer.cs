    public override string Language
    {
      get => "Deutsch";
      set { }
    }

    public override string Execute(string input)
    {
      input = input.Length < _max ? SpecialTokenizerCleanup(input) : SpecialTokenizerCleanupForExtraLongInput(input);

      int length;
      do
      {
        length = input.Length;
        input = input.Replace("  ", " ");
      } while (length != input.Length);

      return input.Replace("< ENDOFCORPUSEXPLORERFILE >", "<ENDOFCORPUSEXPLORERFILE>").Trim().Replace(" ", Environment.NewLine);
    }

    private string SpecialTokenizerCleanup(string str)
    {
      var input = new StringBuilder(str);

      try
      {
        // Klammer und eckige Klammer mit Abständen:
        // "("  -> " ( "   (öffnet Klammer mit Abstand)
        // "["  -> " [ "   (öffnet eckige Klammer mit Abstand)
        // ")"  -> " ) "   (schließt Klammer mit Abstand)
        input = _conv1.Aggregate(input, (current, pair) => current.Replace(pair.Key, pair.Value));
      }
      catch (Exception ex)
      {
        InMemoryErrorConsole.Log(ex);
      }

      var localDict = new Dictionary<string, string>();
      try
      {
        // Erkennung von Token mit Genderzeichen
        // "Student*innen" -> "(G[0])"  (Token mit Genderzeichen wird durch Platzhalter ersetzt)
        var matches = new HashSet<string>(_regex.Matches(input.ToString()).Cast<Match>().Select(m => m.Value));        
        foreach (var x in matches)
          localDict.Add(x, $"(G[{localDict.Count}])");
        
        input = localDict.Aggregate(input, (current, pair) => current.Replace(pair.Key, pair.Value)); 
      }
      catch (Exception ex)
      {
        InMemoryErrorConsole.Log(ex);
      }

      try
      {
        // Abkürzungen -> Platzhalter:
        // " a."   -> "([4])"    (kleines "a." wird ersetzt)
        input = _conv2.Aggregate(input, (current, pair) => current.Replace(pair.Key, pair.Value));
      }
      catch (Exception ex)
      {
        InMemoryErrorConsole.Log(ex);
      }

      try
      {
        // Zeichen mit Abständen:
        // "."  -> " . "   (Punkt bekommt Leerzeichen davor und danach)
        // ","  -> " , "   (Komma wird vom Wort getrennt)
        // "\"" -> " \" " (Anführungszeichen wird abgetrennt)
        input = _conv3.Aggregate(input, (current, pair) => current.Replace(pair.Key, pair.Value));
      }
      catch (Exception ex)
      {
        InMemoryErrorConsole.Log(ex);
      }

      try
      {
        // Spezialfälle für URLs:
        // "//t . co/"   -> "//t.co/"    (Twitter-Shortlink wird repariert)
        // "https : //" -> "https://"    (Leerzeichen in https-URL entfernt)
        // "http : //"  -> "http://"     (Leerzeichen in http-URL entfernt)
        input = _conv4.Aggregate(input, (current, pair) => current.Replace(pair.Key, pair.Value));
      }
      catch (Exception ex)
      {
        InMemoryErrorConsole.Log(ex);
      }

      try
      {
        // Platzhalter -> Token mit Genderzeichen
        // "(G[0])" -> "Student*innen" (Platzhalter wird wieder in ursprünglichen Token mit Genderzeichen zurückverwandelt)
        input = localDict.Aggregate(input, (current, pair) => current.Replace(pair.Value, pair.Key));
      }
      catch (Exception ex)
      {
        InMemoryErrorConsole.Log(ex);
      }

      try
      {
        // Platzhalter -> ursprüngliche Abkürzung:
        // "([3])"   -> " A."     (Platzhalter wird wieder in "A." zurückverwandelt)
        input = _conv2.Aggregate(input, (current, pair) => current.Replace(pair.Value, pair.Key));
      }
      catch (Exception ex)
      {
        InMemoryErrorConsole.Log(ex);
      }

      return input.ToString();
    }

    private string SpecialTokenizerCleanupForExtraLongInput(string input)
    {
      var cut = input.Length / _max;
      var slots = new string[input.Length % _max == 0 ? cut : cut + 1];
      Parallel.For(
                   0,
                   slots.Length,
                   Configuration.ParallelOptions,
                   i =>
                   {
                     var pos = i * _max;
                     slots[i] = SpecialTokenizerCleanup(
                                                        input.Substring(pos,
                                                                        pos + _max > input.Length
                                                                          ? input.Length - pos
                                                                          : _max));
                   });

      return string.Concat(slots);
    }
